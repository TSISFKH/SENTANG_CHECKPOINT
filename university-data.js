// ========================================
// แปลงชื่อภูมิภาค
// ========================================

function getRegionName(region) {

    const regions = {

        central:
            "ภาคกลาง",

        north:
            "ภาคเหนือ",

        northeast:
            "ภาคตะวันออกเฉียงเหนือ",

        east:
            "ภาคตะวันออก",

        south:
            "ภาคใต้"

    };

    return regions[region] || region;

}


// ========================================
// แปลงประเภทมหาวิทยาลัย
// ========================================

function getTypeName(type) {

    const types = {

        public:
            "มหาวิทยาลัยรัฐ",

        private:
            "มหาวิทยาลัยเอกชน"

    };

    return types[type] || type;

}


// ========================================
// ค้นหามหาวิทยาลัยตามคณะ
// ========================================

function getUniversitiesByFaculty(facultyName) {

    return Object.keys(universityData).filter(

        universityName =>

            universityData[
                universityName
            ].faculties.includes(
                facultyName
            )

    );

}


